/// Domain-separation string whose `keccak256` IS the CREATE2 `salt` this
/// module deploys (and derives) its `SimpleAccountFactory` under (see
/// [`factory_create2_salt`]). Mirrors `fedimint_usdt_common`'s
/// `POOL_ACCOUNT_DOMAIN`/`DEPOSIT_ADDRESS_DOMAIN` convention: a fixed,
/// documented tag so the factory address is deterministic and domain-separated
/// from any unrelated CREATE2 deploy of the same creation code.
pub const FACTORY_CREATE2_SALT_DOMAIN: &[u8] = b"fedimint-usdt-factory-v0";

/// The fixed 32-byte CREATE2 `salt` (`keccak256(FACTORY_CREATE2_SALT_DOMAIN)`)
/// the module uses both to compute [`derive_account_factory`] and to
/// CREATE2-deploy the factory through [`ARACHNID_DEPLOYER`]. A pure function of
/// a compiled-in constant, so it is byte-identical on every guardian. Mirrors
/// `fedimint_usdt_common::pool_salt`.
#[must_use]
pub fn factory_create2_salt() -> [u8; 32] {
    keccak256(FACTORY_CREATE2_SALT_DOMAIN).0
}

/// The CREATE2 `initCode` the module deploys the `SimpleAccountFactory` from:
/// the vendored [`FACTORY_CREATION_CODE`] concatenated with the ABI-encoding of
/// the factory constructor's single `address _entryPoint` argument
/// (`abi.encode(entry_point)` — a 32-byte left-padded word). Both the
/// config-gen address prediction ([`derive_account_factory`]) and the on-chain
/// deploy use this exact byte string, so the deployed factory lands at exactly
/// the predicted address.
#[must_use]
pub fn factory_init_code(entry_point: EvmAddress) -> Vec<u8> {
    let mut init_code = FACTORY_CREATION_CODE.to_vec();
    // `abi.encode(entryPoint)`: a single static `address` is its left-padded
    // 32-byte word. Mirrors the harness's factory-deploy ctor-arg encoding.
    let ctor_args = (Address::from(entry_point.0),).abi_encode_params();
    init_code.extend_from_slice(&ctor_args);
    init_code
}

/// Deterministically computes this module's `SimpleAccountFactory` address as a
/// pure function of `entry_point` plus vendored constants — the config-gen
/// footing for Part A. Equal to `CREATE2(deployer = ARACHNID_DEPLOYER, salt =
/// factory_create2_salt(), initCode = factory_init_code(entry_point))` per
/// EIP-1014: `keccak256(0xff ‖ deployer ‖ salt ‖ keccak256(initCode))[12..]`.
///
/// No RPC, no wall-clock, no `our_peer_id`: every guardian computes the
/// byte-identical address from the same consensus `entry_point`. Pinned
/// against a real CREATE2 deploy by the live-anvil `factory_pinning` test.
#[must_use]
pub fn derive_account_factory(entry_point: EvmAddress) -> EvmAddress {
    let init_code = factory_init_code(entry_point);
    let deployer = Address::from(ARACHNID_DEPLOYER.0);
    let derived = deployer.create2_from_code(factory_create2_salt(), init_code);
    EvmAddress(derived.into_array())
}

/// The `SimpleAccount` implementation address the factory's constructor
/// deploys as its first internal `CREATE` (`new SimpleAccount(entryPoint)`),
/// i.e. `CREATE(account_factory, nonce = 1)`. A pure function of the factory
/// address; pinned against the factory's on-chain `accountImplementation()` by
/// the live-anvil `factory_pinning` test.
#[must_use]
pub fn derive_simple_account_impl(account_factory: EvmAddress) -> EvmAddress {
    create_address(account_factory, 1)
}

