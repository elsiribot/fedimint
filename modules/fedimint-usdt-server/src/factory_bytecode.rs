//! Vendored `SimpleAccountFactory` **creation** bytecode and the CREATE2
//! machinery Part A uses to deterministically compute — and self-deploy — this
//! module's ERC-4337 `SimpleAccountFactory` from its `entry_point` config.
//!
//! This lives in `fedimint-usdt-server` (NOT `fedimint-usdt-common`): the
//! ~10.7 KB creation bytecode is only needed guardian-side (to predict the
//! factory address at config-gen and to broadcast the on-chain deploy). The
//! `fedimint-usdt-common` crate stays lean/WASM-safe and only needs the
//! already-config'd factory/impl *addresses*, never the creation code.

