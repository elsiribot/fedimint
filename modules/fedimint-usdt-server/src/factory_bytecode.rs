use alloy::sol_types::SolValue as _;
use fedimint_usdt_common::{EvmAddress, create_address};

/// The canonical Arachnid "deterministic-deployment-proxy" CREATE2 deployer
/// contract address, identical on every chain it has been bootstrapped on
/// (mainnet and most public testnets ship it pre-deployed). Passing
/// `salt (32 bytes) ‖ initCode` as calldata to this address CREATE2-deploys
/// `initCode` at `keccak256(0xff ‖ deployer ‖ salt ‖
/// keccak256(initCode))[12..]`.
///
/// Source: <https://github.com/Arachnid/deterministic-deployment-proxy>.
pub const ARACHNID_DEPLOYER: EvmAddress = EvmAddress([
    0x4e, 0x59, 0xb4, 0x48, 0x47, 0xb3, 0x79, 0x57, 0x85, 0x88, 0x92, 0x0c, 0xa7, 0x8f, 0xbf, 0x26,
    0xc0, 0xb4, 0x95, 0x6c,
]);

/// The one-time-use EOA that signed [`ARACHNID_RAW_DEPLOY_TX`] (its `from`,
/// recovered from that transaction's fixed `r == s == 0x2222…2222`
/// signature). On a chain where [`ARACHNID_DEPLOYER`] is not yet present, this
/// account must first be funded with [`ARACHNID_DEPLOY_TX_COST_WEI`] of ETH,
/// after which broadcasting [`ARACHNID_RAW_DEPLOY_TX`] deploys the proxy.
///
/// Source: <https://github.com/Arachnid/deterministic-deployment-proxy>.
pub const ARACHNID_DEPLOYER_SIGNER: EvmAddress = EvmAddress([
    0x3f, 0xab, 0x18, 0x46, 0x22, 0xdc, 0x19, 0xb6, 0x10, 0x93, 0x49, 0xb9, 0x48, 0x11, 0x49, 0x3b,
    0xf2, 0xa4, 0x53, 0x62,
]);

/// The ETH (wei) that must be pre-funded to [`ARACHNID_DEPLOYER_SIGNER`] before
/// broadcasting [`ARACHNID_RAW_DEPLOY_TX`]: `gasLimit (100 000) * gasPrice
/// (100 gwei) = 0.01 ETH`. The transaction's actual gas use is lower (~68 131),
/// so any surplus stays with the signer EOA; funding the full budget matches
/// the canonical project's instructions and guarantees the deploy cannot run
/// out of gas.
pub const ARACHNID_DEPLOY_TX_COST_WEI: u128 = 10_000_000_000_000_000; // 100_000 * 100e9

/// The canonical, pre-signed (pre-EIP-155, one-time-use) raw transaction that
/// deploys the Arachnid CREATE2 proxy at [`ARACHNID_DEPLOYER`]. Broadcast
/// verbatim (after funding [`ARACHNID_DEPLOYER_SIGNER`]) on any chain lacking
/// the proxy. Its fixed `r == s == 0x2222…2222` signature recovers to
/// [`ARACHNID_DEPLOYER_SIGNER`], and the contract it creates lands at
/// [`ARACHNID_DEPLOYER`] — both invariants are pinned by the live-anvil
